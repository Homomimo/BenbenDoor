        XCTAssertNotNil(exchange.acceptSelection(response(opcode: 1)))
        XCTAssertNil(exchange.acceptSelection(response(opcode: 1)))
    }

    func testUnlockCommandCannotBeAutomaticallySubmittedTwice() {
