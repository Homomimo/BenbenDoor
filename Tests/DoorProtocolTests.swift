import XCTest
@testable import BenbenDoor

final class DoorProtocolTests: XCTestCase {
    func testBackgroundUnlockRequiresExplicitOptIn() {
        let deadline = Date(timeIntervalSince1970: 100)
        let instant = Date(timeIntervalSince1970: 90)
        XCTAssertThrowsError(try DoorUnlockPolicy.validate(background: true, enabled: false, foreground: false, deadline: deadline, now: instant))
        XCTAssertNoThrow(try DoorUnlockPolicy.validate(background: true, enabled: true, foreground: false, deadline: deadline, now: instant))
    }

    func testExpiredRequestCannotSendFromForegroundOrBackground() {
        let deadline = Date(timeIntervalSince1970: 100)
        let instant = Date(timeIntervalSince1970: 101)
        for background in [false, true] {
            XCTAssertThrowsError(try DoorUnlockPolicy.validate(background: background, enabled: true, foreground: true, deadline: deadline, now: instant))
        }
    }

    func testOrdinaryUnlockStillRequiresForeground() {
        let deadline = Date(timeIntervalSince1970: 100)
        let instant = Date(timeIntervalSince1970: 90)
        XCTAssertThrowsError(try DoorUnlockPolicy.validate(background: false, enabled: true, foreground: false, deadline: deadline, now: instant))
        XCTAssertNoThrow(try DoorUnlockPolicy.validate(background: false, enabled: false, foreground: true, deadline: deadline, now: instant))
    }
    // Expected values generated by executing the original JS with synthetic IDs.
    private var key: DoorKey {
        DoorKey(schemaVersion: 1, displayName: "测试", deviceID: "123456", advertisedName: "KD-123456",
                agentID: "1234567890", sysID: "0987654321", region: 1, subregion: 9, devID: 1,
                seqNo: 0x33333333, validFrom: "2026-01-01T00:00:00Z", validUntil: "2027-01-01T00:00:00Z",
                timezone: "+08:00", config: "0")
    }
    private var now: Date { DoorKey.parseDate("2026-11-14T06:05:00Z")! }
    private func hex(_ data: Data) -> String { data.map { String(format: "%02x", $0) }.joined() }

    func testIdentifierConversionMatchesOriginal() {
        XCTAssertEqual(DoorProtocol.identifier("1234567890"), 49674)
        XCTAssertEqual(DoorProtocol.identifier("0987654321"), 49577)
    }

    func testSelectMatchesOriginal() {
        XCTAssertEqual(hex(DoorProtocol.select(key)), "2a07010100090001009b9b")
    }

    func testTimeUsesDoorTimezone() throws {
        XCTAssertEqual(try DoorProtocol.packedTime(now, zone: key.timeZone!), 896430240)
        XCTAssertEqual(try DoorProtocol.packedTime(now.addingTimeInterval(59), zone: key.timeZone!), 896430240)
    }

    func testUnlockMatchesOriginal() throws {
        let data = try DoorProtocol.unlock(key, session: 0x1234, minorVersion: 0x99, now: now)
        XCTAssertEqual(data.count, 20)
        XCTAssertEqual(hex(data), "2a1006123400356e70a0356e7140333333331e8b")
    }

    func testFirmwareConfigOptionMatchesOriginal() throws {
        var configured = key; configured.config = "13"
        XCTAssertEqual(hex(try DoorProtocol.unlock(configured, session: 0x1234, minorVersion: 0x99, now: now)),
                       "2a1006123440356e70a0356e714033333333dc84")
        XCTAssertEqual(hex(try DoorProtocol.unlock(configured, session: 0x1234, minorVersion: 0x1F, now: now)),
                       "2a1006123400356e70a0356e7140333333331e8b")
    }

    func testResponsesRequireChecksum() {
        let valid: [UInt8] = [0x3B, 8, 6, 0x12, 0x34, 0, 0, 1, 0, 0, 5, 0x68]
        XCTAssertTrue(DoorProtocol.validResponse(valid))
        var corrupt = valid; corrupt[5] = 4
        XCTAssertFalse(DoorProtocol.validResponse(corrupt))
        XCTAssertFalse(DoorProtocol.validResponse(Array(valid.dropLast())))
    }

    func testExpiryAndMissingSessionFail() throws {
        XCTAssertNoThrow(try key.validate(at: now))
        XCTAssertThrowsError(try key.validate(at: DoorKey.parseDate("2027-02-01T00:00:00Z")!))
        XCTAssertThrowsError(try key.validate(at: DoorKey.parseDate("2025-12-01T00:00:00Z")!))
        XCTAssertThrowsError(try DoorProtocol.unlock(key, session: 0, minorVersion: 0x99, now: now))
    }
}
